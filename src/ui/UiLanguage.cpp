void UiLanguageManager::initialize()
{
    if (auto* state = qtTranslationState()) state->apply(currentLanguage());
}

UiLanguage UiLanguageManager::currentLanguage()
{
    const QString processOverride = qEnvironmentVariable("FIRECAE_UI_LANGUAGE");
    if (processOverride == QStringLiteral("en")) {
        return UiLanguage::English;
    }
    if (processOverride == QStringLiteral("zh_CN")) {
        return UiLanguage::ChineseSimplified;
    }
    QSettings settings;
    const QString saved = settings.value(QString::fromLatin1(languageSettingsKey)).toString();
    if (saved == QStringLiteral("en")) {
        return UiLanguage::English;
    }
    if (saved == QStringLiteral("zh_CN")) {
        return UiLanguage::ChineseSimplified;
    }
    return QLocale::system().language() == QLocale::Chinese
               ? UiLanguage::ChineseSimplified
               : UiLanguage::English;
}

void UiLanguageManager::setCurrentLanguage(UiLanguage language)
{
    QSettings().setValue(QString::fromLatin1(languageSettingsKey), languageCode(language));
    initialize();
}

QString UiLanguageManager::text(const QString& englishText)
{
    if (currentLanguage() != UiLanguage::ChineseSimplified) {
        return englishText;
    }
    return chineseTranslations().value(englishText, englishText);
}

QString UiLanguageManager::languageCode(UiLanguage language)
{
    return language == UiLanguage::ChineseSimplified ? QStringLiteral("zh_CN")
                                                      : QStringLiteral("en");
}
